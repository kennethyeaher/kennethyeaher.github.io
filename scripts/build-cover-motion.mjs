// write src/styles/cover-motion/<slug>.css for each home motion cover and each html exhibit loop from figma's
// get_motion_context output (scripts/cover-motion/<name>.motion.json, saved as returned for the frame with recursive
// true). every css snippet keeps its timings, easings and values; the only change is that each figma px length becomes
// a share of the frame (var(--u)), so the timeline scales with the card. only the home page imports the covers' files,
// and only the elms case study links its send path's.
// usage: node scripts/build-cover-motion.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { coverMotion } from "../src/data/coverMotion.mjs";
import { loopMotion } from "../src/data/loopMotion.mjs";

/** the saved figma motion export for each cover. */
export const motionSources = {
  "college-park-capstone": "capstone",
  ovara: "ovara",
  "kairo-health": "kairo",
  "elms-send-path": "elms-send-path",
};

/** the parsed figma motion export of one cover. */
export function readMotion(slug) {
  return JSON.parse(readFileSync(new URL(`cover-motion/${motionSources[slug]}.motion.json`, import.meta.url), "utf8"));
}

/** a css string with each nonzero px length written as that many figma px of the cover. */
export function scalePx(css) {
  return css.replace(/(-?\d*\.?\d+)px\b/g, (match, value) => (Number(value) === 0 ? match : `calc(${value} * var(--u))`));
}

/** one figma css snippet split into the node's own declarations, its @keyframes rules and any @property rules (a
    rotation runs through a registered custom property, which has to sit at the top level). */
export function splitSnippet(css) {
  const at = css.indexOf("@keyframes ");
  const properties = [];
  const declarations = css.slice(0, at).replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/@property [^{]+\{[^}]*\}/g, (rule) => { properties.push(rule.trim()); return ""; }).trim();
  const keyframes = css.slice(at).split(/(?=@keyframes )/).map((rule) => rule.trim());
  return { declarations, keyframes, properties };
}

/** each animated node's snippet on its node id under scope, checked against the frame and the timeline length. */
function timelineCss(slug, motion, scope) {
  const { nodes, timelineCohorts: [cohort] } = readMotion(slug);
  if (cohort.rootNodeId !== motion.figma) throw new Error(`${slug} export is for ${cohort.rootNodeId}, not ${motion.figma}`);
  if (cohort.durationMs !== motion.seconds * 1000) throw new Error(`${slug} loops ${cohort.durationMs}ms, not ${motion.seconds}s`);
  const lines = [];
  for (const node of nodes) {
    const css = node.codeSnippets?.css;
    if (!css) throw new Error(`${slug} ${node.nodeId} has no css snippet`);
    const { declarations, keyframes, properties } = splitSnippet(css);
    for (const [, seconds] of declarations.matchAll(/ ([\d.]+)s linear/g)) {
      if (Number(seconds) !== motion.seconds) throw new Error(`${slug} ${node.nodeId} runs ${seconds}s, off the ${motion.seconds}s timeline`);
    }
    lines.push(`/* ${node.nodeName} */`, ...properties, `${scope} [data-node="${node.nodeId}"] { ${scalePx(declarations)} }`, ...keyframes.map(scalePx));
  }
  return lines;
}

/** the stylesheet of one cover: each animated node's snippet on its node id, then the play and reduced motion rules. */
export function coverMotionCss(slug) {
  const motion = coverMotion[slug];
  const scope = `.project-cover[data-motion="${slug}"]`;
  const lines = [
    `/* generated by scripts/build-cover-motion.mjs from figma ${motion.figma} (scripts/cover-motion/${motionSources[slug]}.motion.json); do not edit. */`,
    `/* one figma px is 1/454 of the cover's width, resolved against the card (the cover is its container). */`,
    `${scope} { --u: calc(100cqi / 454); }`,
    ...timelineCss(slug, motion, scope),
  ];
  lines.push(
    `/* the timeline holds until the cover is on screen (exhibits.ts sets is-live on the field and the motion layer). */`,
    `${scope} :is(.cover-gradient, .cover-motion):not(.is-live) [data-node] { animation-play-state: paused; }`,
    `/* reduced motion holds one frame: ${motion.still}s in, where the first scene has landed. the site's reduce rule cuts
   every animation to 0.01ms once (global.css), which would drop the cover back to its unanimated layers, so the
   timeline's own length comes back here, paused. */`,
    `@media (prefers-reduced-motion: reduce) { ${scope} [data-node][data-node] { animation-duration: ${motion.seconds}s !important; animation-iteration-count: infinite !important; animation-delay: -${motion.still}s; animation-play-state: paused; } }`,
  );
  return `${lines.join("\n")}\n`;
}

/** the stylesheet of one html exhibit loop: the timeline held at its still until the loop is live. the still holds
    without scripts, off screen, when the visitor pauses and under reduced motion, so the loop always opens on its first
    full frame (frame 0 is the camera fading in) and plays on from there. */
export function loopMotionCss(slug) {
  const motion = loopMotion[slug];
  const scope = `[data-motion-loop="${slug}"]`;
  return `${[
    `/* generated by scripts/build-cover-motion.mjs from figma ${motion.figma} (scripts/cover-motion/${motionSources[slug]}.motion.json); do not edit. */`,
    `/* one figma px is 1/${motion.width} of the loop's width (the loop frame is its own container). */`,
    `${scope} { --u: calc(100cqi / ${motion.width}); }`,
    ...timelineCss(slug, motion, scope),
    `/* every layer starts ${motion.still}s in, the first full frame, and holds there until exhibits.ts sets is-live on the frame. */`,
    `${scope} [data-node][data-node] { animation-delay: -${motion.still}s; }`,
    `${scope}:not(.is-live) [data-node] { animation-play-state: paused; }`,
    `/* the site's reduce rule cuts every animation to 0.01ms once (global.css), which would drop the loop to its
   unanimated layers, so the timeline's own length comes back here, paused on the still. */`,
    `@media (prefers-reduced-motion: reduce) { ${scope} [data-node][data-node] { animation-duration: ${motion.seconds}s !important; animation-iteration-count: infinite !important; animation-delay: -${motion.still}s; animation-play-state: paused; } }`,
  ].join("\n")}\n`;
}

/** where a cover's or a loop's stylesheet lives. */
export function coverMotionPath(slug) {
  return fileURLToPath(new URL(`../src/styles/cover-motion/${slug}.css`, import.meta.url));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(fileURLToPath(new URL("../src/styles/cover-motion/", import.meta.url)), { recursive: true });
  for (const slug of Object.keys(coverMotion)) writeFileSync(coverMotionPath(slug), coverMotionCss(slug));
  for (const slug of Object.keys(loopMotion)) writeFileSync(coverMotionPath(slug), loopMotionCss(slug));
  console.log(`wrote ${Object.keys(motionSources).length} motion stylesheets`);
}
